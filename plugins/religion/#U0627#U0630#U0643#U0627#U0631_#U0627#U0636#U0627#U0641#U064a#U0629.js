const MASAA = [
    'أَمْسَيْنَا وَأَمْسَى الْمُلْكُ للهِ، وَالْحَمْدُ للهِ، لاَ إِلَهَ إِلاَّ اللهُ وَحْدَهُ لاَ شَرِيكَ لَهُ',
    'اللَّهُمَّ بِكَ أَمْسَيْنَا، وَبِكَ أَصْبَحْنَا، وَبِكَ نَحْيَا، وَبِكَ نَمُوتُ وَإِلَيْكَ الْمَصِيرُ',
    'اللَّهُمَّ مَا أَمْسَى بِي مِنْ نِعْمَةٍ أَوْ بِأَحَدٍ مِنْ خَلْقِكَ فَمِنْكَ وَحْدَكَ لاَ شَرِيكَ لَكَ، فَلَكَ الْحَمْدُ وَلَكَ الشُّكْرُ',
    'أَعُوذُ بِكَلِمَاتِ اللهِ التَّامَّاتِ مِنْ شَرِّ مَا خَلَقَ'
];

const NAWM = [
    'بِاسْمِكَ اللَّهُمَّ أَمُوتُ وَأَحْيَا',
    'اللَّهُمَّ أَسْلَمْتُ نَفْسِي إِلَيْكَ، وَفَوَّضْتُ أَمْرِي إِلَيْكَ، وَوَجَّهْتُ وَجْهِي إِلَيْكَ',
    'سُبْحَانَ اللهِ (٣٣) وَالْحَمْدُ للهِ (٣٣) وَاللهُ أَكْبَرُ (٣٤)',
    'اللَّهُمَّ قِنِي عَذَابَكَ يَوْمَ تَبْعَثُ عِبَادَكَ'
];

const DUAS = [
    'اللهم اجعل هذا اليوم خير أيامنا وأعظمها بركة',
    'ربنا آتنا في الدنيا حسنة وفي الآخرة حسنة وقنا عذاب النار',
    'اللهم اشرح لي صدري ويسر لي أمري',
    'اللهم إني أسألك العفو والعافية في الدنيا والآخرة',
    'اللهم اجعلني من عبادك الذين إذا أحسنوا استبشروا وإذا أساؤوا استغفروا',
    'اللهم اهدني فيمن هديت وعافني فيمن عافيت'
];

const handler = async (m, { conn, command }) => {
    const map = { 'اذكار_المساء': { list: MASAA, title: '🌇 *أذكار المساء*' }, 'اذكار_النوم': { list: NAWM, title: '🌙 *أذكار النوم*' }, 'دعاء': { list: DUAS, title: '🤲 *دعاء*' } };
    const item = map[command];
    if (!item) return;

    const text = item.list[Math.floor(Math.random() * item.list.length)];
    await conn.sendMessage(m.chat, {
        text:
            `┌──────────────────┐\n│  ${item.title}  │\n└──────────────────┘\n\n` +
            `*${text}*\n\n> _تقبل الله منا ومنكم_`
    }, { quoted: m });
};

handler.usage    = ['اذكار_المساء', 'اذكار_النوم', 'دعاء'];
handler.category = 'religion';
handler.command  = ['اذكار_المساء', 'اذكار_النوم', 'دعاء'];
handler.cooldown = 2000;

export default handler;
