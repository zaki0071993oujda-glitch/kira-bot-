const handler = async (m, { conn, command, text }) => {
    if (command === 'اسماء_الله_الحسنى') {
        const list = NAMES.map((n, i) => `${i + 1}. ${n}`).join('\n');
        return conn.sendMessage(m.chat, {
            text: `╭─┈─┈─⟞📿⟝─┈─┈─╮\n┃ *أسماء الله الحسنى*\n╰─┈─┈─⟞🕌⟝─┈─┈─╯\n\n${list}\n\n> اعرف معنى اسم بكتابة: \`معنى_اسم_الله الاسم\``
        }, { quoted: m });
    }

    if (command === 'معنى_اسم_الله') {
        const name = text?.trim();
        if (!name) return m.reply('*⚠️ اكتب اسم من أسماء الله*\n> مثال: `معنى_اسم_الله الرحمن`');
        const meaning = MEANINGS[name];
        if (!meaning) {
            if (!NAMES.includes(name)) return m.reply('*⚠️ الاسم ده مش في القائمة، شوف `اسماء_الله_الحسنى`*');
            return m.reply(`*"${name}"* من أسماء الله الحسنى، ومعناه التفصيلي مش متوفر عندي دلوقتي 🙏`);
        }
        return conn.sendMessage(m.chat, {
            text: `📿 *${name}*\n\n${meaning}`
        }, { quoted: m });
    }
};

handler.usage    = ['اسماء_الله_الحسنى', 'معنى_اسم_الله'];
handler.category = 'islamic';
handler.command  = ['اسماء_الله_الحسنى', 'معنى_اسم_الله'];
handler.cooldown = 2000;

export default handler;
