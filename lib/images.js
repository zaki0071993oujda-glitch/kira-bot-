// ─── الحصول على صورة حسب المستوى ──────────────────────
export function getLevelImage(level) {
    const levels = Object.keys(LEVEL_IMAGES).map(Number).sort((a, b) => a - b);
    let closest = levels[0];
    for (const lvl of levels) {
        if (lvl <= level) closest = lvl;
    }
    return LEVEL_IMAGES[closest] || LEVEL_IMAGES[1];
}

// ─── الحصول على صورة عشوائية ──────────────────────────
export function getRandomImage() {
    return RANDOM_IMAGES[Math.floor(Math.random() * RANDOM_IMAGES.length)];
}

